package main

import (
	"net"
	"testing"
	"time"
)

// udpListener binds an ephemeral loopback UDP socket for tests.
func udpListener(t *testing.T) *net.UDPConn {
	t.Helper()
	addr, err := net.ResolveUDPAddr("udp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	conn, err := net.ListenUDP("udp", addr)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { conn.Close() })
	return conn
}

// recvPDU reads one datagram and decodes it as an SNMP message.
func recvPDU(t *testing.T, conn *net.UDPConn, wait time.Duration) *pdu {
	t.Helper()
	conn.SetReadDeadline(time.Now().Add(wait))
	buf := make([]byte, 65535)
	n, _, err := conn.ReadFromUDP(buf)
	if err != nil {
		return nil
	}
	_, p, err := decodeMessage(buf[:n])
	if err != nil {
		t.Fatalf("decode notification: %v", err)
	}
	return p
}

func newTestTrapSender(t *testing.T, cfg *config) *trapSender {
	t.Helper()
	if cfg == nil {
		cfg = defaultConfig()
	}
	cfg.InformTimeoutMS = 60
	cfg.InformRetries = 2
	ts := newTrapSender(cfg)
	ts.setConn(udpListener(t))
	t.Cleanup(ts.close)
	return ts
}

func informVarbinds() []varbind {
	return []varbind{
		{oid: []int{1, 3, 6, 1, 2, 1, 1, 3, 0}, tag: tagTimeTicks,
			value: uint32(0)},
		{oid: []int{1, 3, 6, 1, 6, 3, 1, 1, 4, 1, 0}, tag: tagOID,
			value: []int{1, 3, 6, 1, 6, 3, 1, 1, 5, 1}},
	}
}

func TestInformRetransmitAndAckDedup(t *testing.T) {
	manager := udpListener(t)
	ts := newTestTrapSender(t, nil)
	ts.setManagerAddr(manager.LocalAddr().(*net.UDPAddr))

	if err := ts.sendInform(informVarbinds()); err != nil {
		t.Fatal(err)
	}
	// Initial send plus retransmissions until acked.
	first := recvPDU(t, manager, time.Second)
	if first == nil || first.tag != pduInformRequest {
		t.Fatalf("first inform: %+v", first)
	}
	second := recvPDU(t, manager, time.Second)
	if second == nil || second.requestID != first.requestID {
		t.Fatalf("retransmit: %+v", second)
	}
	// Acknowledge; the response arrives at the agent's dispatch path.
	ts.handleResponse(&pdu{tag: pduResponse, requestID: first.requestID},
		manager.LocalAddr().(*net.UDPAddr))
	// Duplicate ack must be a no-op (no panic, no new inform).
	ts.handleResponse(&pdu{tag: pduResponse, requestID: first.requestID},
		manager.LocalAddr().(*net.UDPAddr))
	// No further retransmissions after the ack.
	if p := recvPDU(t, manager, 300*time.Millisecond); p != nil {
		t.Fatalf("inform after ack: %+v", p)
	}
	// And no duplicate inform was generated by the duplicate ack.
	if p := recvPDU(t, manager, 200*time.Millisecond); p != nil {
		t.Fatalf("duplicate ack generated traffic: %+v", p)
	}
}

func TestInformRetransmitUsesLatestManagerAddr(t *testing.T) {
	mgr1 := udpListener(t)
	mgr2 := udpListener(t)
	ts := newTestTrapSender(t, nil)
	ts.setManagerAddr(mgr1.LocalAddr().(*net.UDPAddr))

	if err := ts.sendInform(informVarbinds()); err != nil {
		t.Fatal(err)
	}
	// First attempt goes to mgr1.
	if p := recvPDU(t, mgr1, time.Second); p == nil {
		t.Fatal("first inform not sent to mgr1")
	}
	// Manager address changes before the first retransmission.
	ts.setManagerAddr(mgr2.LocalAddr().(*net.UDPAddr))
	// The retransmission must go to mgr2, not mgr1.
	if p := recvPDU(t, mgr2, time.Second); p == nil {
		t.Fatal("retransmit not sent to latest manager address")
	}
	if p := recvPDU(t, mgr1, 300*time.Millisecond); p != nil {
		t.Fatalf("stale manager still receives retransmits: %+v", p)
	}
}

func TestTrapSentToConfiguredTargets(t *testing.T) {
	target := udpListener(t)
	cfg := defaultConfig()
	cfg.TrapTargets = []string{target.LocalAddr().String()}
	ts := newTestTrapSender(t, cfg)

	if err := ts.sendTrap(informVarbinds()); err != nil {
		t.Fatal(err)
	}
	p := recvPDU(t, target, time.Second)
	if p == nil || p.tag != pduTrapV2 {
		t.Fatalf("trap: %+v", p)
	}
	if len(p.varbinds) != 2 {
		t.Fatalf("trap varbinds: %d", len(p.varbinds))
	}
}
